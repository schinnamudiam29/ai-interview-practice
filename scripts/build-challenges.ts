/**
 * Bundles every challenge package under /challenges (plus the sandbox test
 * runner) into a generated TypeScript module that only server code imports.
 * Runs automatically before `dev`, `build` and `test`.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(__dirname, "..");
const challengesDir = join(root, "challenges");
const outDir = join(root, "src", "lib", "challenges");
const outFile = join(outDir, "bundle.generated.ts");

function readTree(dir: string, base = dir): Record<string, string> {
  const out: Record<string, string> = {};
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir).sort()) {
    if (name === "__pycache__" || name.startsWith(".")) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) Object.assign(out, readTree(full, base));
    else out[relative(base, full).split("\\").join("/")] = readFileSync(full, "utf8");
  }
  return out;
}

const readJson = (p: string) => JSON.parse(readFileSync(p, "utf8"));
const readText = (p: string) => (existsSync(p) ? readFileSync(p, "utf8") : "");

const packages = readdirSync(challengesDir)
  .filter((d) => statSync(join(challengesDir, d)).isDirectory())
  .sort()
  .map((slug) => {
    const dir = join(challengesDir, slug);
    const meta = readJson(join(dir, "challenge.json"));
    if (meta.slug !== slug) throw new Error(`${slug}: challenge.json slug mismatch`);
    const pkg = {
      meta,
      brief: readText(join(dir, "brief.md")),
      twist: readText(join(dir, "twist", "twist.md")),
      starter: readTree(join(dir, "starter")),
      hidden: readTree(join(dir, "hidden")),
      twistTests: readTree(join(dir, "twist", "tests"), join(dir, "twist")),
      solution: readTree(join(dir, "solution")),
      hints: readJson(join(dir, "hints.json")),
      policy: readJson(join(dir, "policy.json")),
      rubric: readJson(join(dir, "rubric.json")),
    };
    const version = createHash("sha256").update(JSON.stringify(pkg)).digest("hex").slice(0, 12);
    return { ...pkg, version };
  });

const runner = readFileSync(join(root, "runner", "run_tests.py"), "utf8");

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/build-challenges.ts. Do not edit.\n` +
    `// Contains hidden tests and reference solutions: import only from server code.\n` +
    `import "server-only";\n` +
    `import type { ChallengePackage } from "./types";\n\n` +
    `export const CHALLENGES: ChallengePackage[] = ${JSON.stringify(packages, null, 1)};\n\n` +
    `export const RUNNER_SOURCE: string = ${JSON.stringify(runner)};\n`,
);
console.log(`bundled ${packages.length} challenge(s) -> ${relative(root, outFile)}`);
